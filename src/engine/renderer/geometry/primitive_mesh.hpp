#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <vector>

namespace SNE::Engine::Renderer {
    /**
     * @brief Defines the vertex attributes shared by built-in primitives.
     *
     * Stores position, normal, texture coordinates, and tangent-space
     * information for CPU-generated primitive geometry.
     *
     * The vertex representation is independent of graphics APIs and
     * can be consumed by the existing mesh upload infrastructure.
     *
     * @note Specialized geometry is not required to use this vertex format.
     */
    struct PrimitiveVertex {
        /** @brief Number of floating-point components in a 3D vector. */
        static constexpr std::size_t kSpatialComponentCount{3U};

        /** @brief Number of floating-point components in a UV coordinate. */
        static constexpr std::size_t kUvComponentCount{2U};

        /** @brief Number of tangent-direction and handedness components. */
        static constexpr std::size_t kTangentComponentCount{4U};

        /**
         * @brief Position relative to the primitive's local origin.
         */
        std::array<float, kSpatialComponentCount> position{};

        /**
         * @brief Surface normal expressed in local-space coordinates.
         *
         * Generated primitives provide outward-facing unit normals.
         */
        std::array<float, kSpatialComponentCount> normal{};

        /**
         * @brief Two-dimensional texture coordinates.
         *
         * Built-in primitive generators provide normalized UV coordinates
         * according to their respective mapping conventions.
         */
        std::array<float, kUvComponentCount> uv{};

        /**
         * @brief Tangent-space direction and handedness.
         *
         * The first three components describe the local-space tangent.
         *
         * The fourth component stores the handedness used to reconstruct
         * the bitangent from the surface normal and tangent.
         */
        std::array<float, kTangentComponentCount> tangent{};
    };

    /**
     * @brief Owns CPU-side geometry for a built-in primitive.
     *
     * Stores vertices and triangle indices generated by reusable
     * primitive geometry functions.
     *
     * The geometry remains independent of Vulkan and does not
     * allocate or own GPU resources.
     *
     * Vertex and index storage is owned by this structure and may
     * be borrowed by the existing mesh upload infrastructure.
     *
     * @note Indices use 16-bit storage to match the current mesh upload
     * contract. Generators must ensure their vertices are indexable.
     *
     * @note Other geometry representations may use different vertex
     * formats and index types as the renderer evolves.
     */
    struct PrimitiveMesh {
        /**
         * @brief Contiguous vertex storage for the generated primitive.
         */
        std::vector<PrimitiveVertex> vertices;

        /**
         * @brief Triangle indices referencing vertices in this mesh.
         *
         * Every index must reference a valid vertex.
         * Each consecutive group of three indices defines a triangle.
         */
        std::vector<std::uint16_t> indices;
    };
} // namespace SNE::Engine::Renderer
